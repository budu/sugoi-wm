/// The `PointerRoot` focus target.
const POINTER_ROOT: Window = 1;
/// `NormalState` in `WM_STATE` (ICCCM 4.1.3.1).
const NORMAL_STATE: u32 = 1;
/// [F3] Buttons that focus on click; the wheel (4 and 5) is not grabbed.
const CLICKS: [ButtonIndex; 3] = [ButtonIndex::M1, ButtonIndex::M2, ButtonIndex::M3];

/// A managed window.
struct Client {
    hints: Hints,
    /// [U1]
    info: Info,
    /// [A3] The unit of its process when it was managed, for hooks.
    unit: Option<String>,
    /// The border width before sugoi managed the window, restored on withdrawal.
    border_width: u16,
    /// The outer rectangle the window has when it floats.
    rect: Rect,
    /// The outer rectangle and border sugoi last configured.
    placed: Option<(Rect, u16)>,
    floating: bool,
    maximized: bool,
    fullscreen: bool,
    on_top: bool,
    minimized: bool,
    /// [V1] The workspace index, 0 to 29.
    workspace: usize,
    /// [V2] Whether sugoi has the window mapped.
    mapped: bool,
    /// [Y3] The window's share of the stack column.
    share: f32,
    /// [W6] [V2] The sequence numbers of sugoi's unmaps whose `UnmapNotify` has not come
    /// yet: an event generated by one of them carries its number, and an unmap by the
    /// client before it a smaller one.
    unmaps: VecDeque<u16>,
}

/// [F4] The ICCCM properties that decide how a window takes focus and closes.
#[derive(Clone, Copy)]
struct Hints {
    /// The `WM_HINTS` input flag, true when absent.
    accepts_input: bool,
    take_focus: bool,
    delete_window: bool,
}

impl Hints {
    fn focusable(self) -> bool {
        self.accepts_input || self.take_focus
    }
}

/// Why the event loop ends.
#[derive(Clone, Copy, PartialEq, Eq)]
enum Exit {
    Quit,
    Restart,
}

